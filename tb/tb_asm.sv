module tb_asm;

    logic clk;
    logic rst;

    logic [31:0] pc;
    logic [31:0] instr;

    logic [31:0] mem_addr;
    logic [31:0] mem_wdata;
    logic [31:0] mem_rdata;

    logic        mem_we;
    logic [3:0]  mem_wstrb;


    logic [31:0] imem [0:255];
    logic [31:0] dmem [0:63];


    integer i;


    // ============================================================
    // DUT
    // ============================================================

    cpu_core dut (
        .clk       (clk),
        .rst       (rst),

        .timer_irq (1'b0),

        .instr     (instr),
        .pc        (pc),

        .mem_addr  (mem_addr),
        .mem_wdata (mem_wdata),
        .mem_rdata (mem_rdata),

        .mem_we    (mem_we),
        .mem_wstrb (mem_wstrb)
    );


    // ============================================================
    // Clock
    // ============================================================

    initial begin

        clk = 1'b0;

        forever #5
            clk = ~clk;

    end


    // ============================================================
    // Instruction memory
    // ============================================================

    always_comb begin

        if (pc < 32'd1024)
            instr = imem[pc[9:2]];
        else
            instr = 32'h00000013;

    end


    // ============================================================
    // Data memory read
    // ============================================================

    always_comb begin

        mem_rdata =
            dmem[mem_addr[7:2]];

    end


    // ============================================================
    // Data memory write
    // ============================================================

    always_ff @(posedge clk) begin

        if (!rst && mem_we) begin

            if (mem_wstrb[0])
                dmem[mem_addr[7:2]][7:0] <= mem_wdata[7:0];

            if (mem_wstrb[1])
                dmem[mem_addr[7:2]][15:8] <= mem_wdata[15:8];

            if (mem_wstrb[2])
                dmem[mem_addr[7:2]][23:16] <= mem_wdata[23:16];

            if (mem_wstrb[3])
                dmem[mem_addr[7:2]][31:24] <= mem_wdata[31:24];

        end

    end


    // ============================================================
    // Test
    // ============================================================

    initial begin

        rst = 1'b1;


        for (i = 0; i < 256; i = i + 1)
            imem[i] = 32'h00000013;


        for (i = 0; i < 64; i = i + 1)
            dmem[i] = 32'b0;


        // Load program generated by RISC-V toolchain
        $readmemh(
            "build/asm/rv32i_smoke.hex",
            imem
        );


        $dumpfile(
            "build/asm/rv32i_smoke.vcd"
        );

        $dumpvars(
            0,
            tb_asm
        );


        repeat (2)
            @(posedge clk);


        @(negedge clk);

        rst = 1'b0;


        // Program is very short.
        // Give it plenty of time to reach pass/fail loop.

        repeat (30)
            @(posedge clk);


        #1;


        $display("");
        $display("==============================");
        $display("      RV32I ASM TEST");
        $display("==============================");

        $display(
            "x3  = %08x",
            dut.u_regfile.regs[3]
        );

        $display(
            "x4  = %08x",
            dut.u_regfile.regs[4]
        );

        $display(
            "x31 = %08x",
            dut.u_regfile.regs[31]
        );

        $display(
            "dmem[0] = %08x",
            dmem[0]
        );


        if (
            dut.u_regfile.regs[31] === 32'd1
            &&
            dut.u_regfile.regs[3] === 32'd30
            &&
            dut.u_regfile.regs[4] === 32'd30
            &&
            dmem[0] === 32'd30
        ) begin

            $display("");
            $display("==============================");
            $display("    RV32I ASM TEST PASS");
            $display("==============================");

        end

        else begin

            $display("");
            $display("==============================");
            $display("    RV32I ASM TEST FAILED");
            $display("==============================");

            $fatal(
                1,
                "Assembly program failed"
            );

        end


        $finish;

    end

endmodule