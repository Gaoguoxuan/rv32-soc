.section .text.start
.globl _start

_start:

    # ============================================================
    # Stack
    # ============================================================

    la sp, __stack_top


    # ============================================================
    # Clear .bss
    # ============================================================

    la t0, __bss_start
    la t1, __bss_end

bss_clear_loop:

    bgeu t0, t1, bss_clear_done

    sw zero, 0(t0)

    addi t0, t0, 4

    j bss_clear_loop


bss_clear_done:


    # ============================================================
    # Enter C
    # ============================================================

    call main


    # ============================================================
    # main should return 42
    # ============================================================

    li t0, 42

    bne a0, t0, fail


    li t6, 1


pass:

    j pass


fail:

    li t6, -1


fail_loop:

    j fail_loop