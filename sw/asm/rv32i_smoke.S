.section .text.start
.globl _start

_start:

    # ------------------------------------------------
    # Basic arithmetic
    # ------------------------------------------------

    addi x1, x0, 10
    addi x2, x0, 20
    add  x3, x1, x2

    # x3 = 30


    # ------------------------------------------------
    # Store / Load
    # ------------------------------------------------

    sw   x3, 0(x0)
    lw   x4, 0(x0)

    # x4 must be 30


    # ------------------------------------------------
    # Branch
    # ------------------------------------------------

    bne  x4, x3, fail


    # ------------------------------------------------
    # LUI + SRLI
    # ------------------------------------------------

    lui  x5, 0x12345
    srli x6, x5, 4


    # ------------------------------------------------
    # PASS signature
    # ------------------------------------------------

    addi x31, x0, 1


pass:
    jal x0, pass


fail:
    addi x31, x0, -1
    jal  x0, fail